-- FUNCTIONS
-- ==========================================

CREATE OR REPLACE FUNCTION get_appointment(p_company_nickname VARCHAR, p_employee_name VARCHAR)
RETURNS TABLE (name VARCHAR, duration INT, scheduled TIMESTAMP) AS $$
BEGIN
    IF p_employee_name IS NULL OR TRIM(p_employee_name) = '' THEN
        RETURN QUERY
SELECT u.name, cs.name, s.duration, a.scheduled, a.status
FROM APPOINTMENTS a
         JOIN USERS u ON a.user_id = u.id
         JOIN SERVICES s ON a.service_id = s.id
         JOIN COMPANY c ON a.company_id = c.id
        JOIN CUSTOMER cs on a.customer_id = cs.id
WHERE c.nickname = p_company_nickname
  AND a.scheduled > CURRENT_TIMESTAMP;
ELSE
        RETURN QUERY
SELECT u.name, cs.name, s.duration, a.scheduled, a.status
FROM APPOINTMENTS a
         JOIN USERS u ON a.user_id = u.id
         JOIN SERVICES s ON a.service_id = s.id
         JOIN COMPANY c ON a.company_id = c.id
         JOIN CUSTOMER cs on a.customer_id = cs.id
WHERE c.nickname = p_company_nickname
  AND u.name = p_employee_name
  AND a.scheduled > CURRENT_TIMESTAMP;
END IF;
END;
$$ LANGUAGE plpgsql;